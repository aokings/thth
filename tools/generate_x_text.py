"""Regenerate thth/adapters/_x_text_data.py from pinned twitter-text / twemoji-parser files.

Usage: python tools/generate_x_text.py SOURCE_DIRECTORY OUTPUT_PY

SOURCE_DIRECTORY holds the three files below, downloaded from the pinned commits
(raw.githubusercontent.com). No network access here and no runtime dependency:
the output is plain Python data. See docs/リリースノート_3.20.0_2026-10-15.md.

- validGTLD.js / validCCTLD.js — twitter/twitter-text@30e2430d90cff3b46393ea54caf511441983c260
  js/src/regexp/ (Apache License 2.0)
- regex.js — twitter/twemoji-parser@f8312f35fdee0e79874bb50213c4544c14fa759b (v14.0.0)
  src/lib/regex.js (MIT License)
"""
from pathlib import Path
import hashlib
import re
import sys

TWITTER_TEXT_COMMIT = '30e2430d90cff3b46393ea54caf511441983c260'
TWEMOJI_PARSER_COMMIT = 'f8312f35fdee0e79874bb50213c4544c14fa759b'
SOURCES = {
    'validGTLD.js': 'b1379fe8b005d027692a05ba0db3e857020c4abd20b7dd62f1026b513c5779e6',
    'validCCTLD.js': 'a05a9ab87869fe8b3456a65ccdadf7e96c6eda40ca02c1874a8e7d0c4ff291f5',
    'regex.js': 'f12140db2388228cc8ba80c7d041d7c5cd29dfbdf7d764acaabc6c34812eca4f',
}
TLD_HEAD = '(?:(?:'
TLD_TAIL = ')(?=[^0-9a-zA-Z@+-]|$))'


def read(root, name):
    data = (root / name).read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCES[name]:
        raise ValueError('input hash mismatch: ' + name)
    return data.decode('utf-8')


def tlds(source):
    start = source.index('RegExp(')
    body = ''.join(re.findall(r"'((?:[^'\\]|\\.)*)'", source[start:]))
    if not (body.startswith(TLD_HEAD) and body.endswith(TLD_TAIL)):
        raise ValueError('unexpected TLD regex shape')
    names = body[len(TLD_HEAD):-len(TLD_TAIL)].split('|')
    if not names or any(not n or re.search(r'[\\()\[\]?*+]', n) for n in names):
        raise ValueError('unexpected TLD entry')
    return names


def emoji_pattern(source):
    match = re.search(r'export default /(.*)/g;\s*$', source, re.S)
    if not match:
        raise ValueError('unexpected emoji regex shape')
    pattern = match.group(1)
    if '\n' in pattern:
        raise ValueError('unexpected emoji regex characters')
    return pattern


def main(argv):
    root, out = Path(argv[1]), Path(argv[2])
    gtld = tlds(read(root, 'validGTLD.js'))
    cctld = tlds(read(root, 'validCCTLD.js'))
    emoji = emoji_pattern(read(root, 'regex.js'))
    lines = [
        '# Generated by tools/generate_x_text.py; do not hand edit.',
        '#',
        '# (full commit hashes live in tools/generate_x_text.py; the 40-hex form would trip',
        '#  tests/test_secrets_grep.py, so only the first 12 characters are written here.)',
        '# GTLD / CCTLD: twitter/twitter-text@' + TWITTER_TEXT_COMMIT[:12],
        '#   js/src/regexp/validGTLD.js, validCCTLD.js',
        '#   Copyright 2018 Twitter, Inc. Licensed under the Apache License, Version 2.0',
        '#   http://www.apache.org/licenses/LICENSE-2.0',
        '# EMOJI_PATTERN: twitter/twemoji-parser@' + TWEMOJI_PARSER_COMMIT[:12] + ' (v14.0.0)',
        '#   src/lib/regex.js — Copyright (c) 2018 Twitter, Inc. MIT License',
        '#   (written over UTF-16 code units, as in JavaScript)',
        '',
        'TWITTER_TEXT_COMMIT = ' + repr(TWITTER_TEXT_COMMIT[:12]),
        'TWEMOJI_PARSER_COMMIT = ' + repr(TWEMOJI_PARSER_COMMIT[:12]),
        '',
        'GTLD = (',
    ]
    lines += ['    ' + repr(name) + ',' for name in gtld]
    lines += [')', '', 'CCTLD = (']
    lines += ['    ' + repr(name) + ',' for name in cctld]
    lines += [')', '', 'EMOJI_PATTERN = (']
    lines += ['    ' + repr(emoji[i:i + 72]) for i in range(0, len(emoji), 72)]
    lines += [')', '']
    out.write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    main(sys.argv)
